def ingest_ctri_dataset(db: Session) -> int:
    """
    Ingest or sync all 10 real CTRI records into the PostgreSQL/SQLite database.
    Idempotently updates existing trials/sites and inserts new ones.
    Returns total count of imported real sites.
    """
    total_sites_count = 0

    for item in CTRI_DATASET:
        trial_dict = dict(item)
        sites_list = [dict(s) for s in trial_dict.pop("sites", [])]
        trial_id = trial_dict["trial_id"]
        t_id = trial_dict.get("id")

        existing_trial = db.query(Trial).filter((Trial.trial_id == trial_id) | (Trial.id == t_id)).first()
        if not existing_trial:
            new_trial = Trial(**trial_dict)
            db.add(new_trial)
            db.flush()
            existing_trial = new_trial
        else:
            # Update CTRI fields on existing trial
            for k, v in trial_dict.items():
                if hasattr(existing_trial, k):
                    setattr(existing_trial, k, v)
            db.flush()

        # Ingest/sync sites for this trial
        for site_dict in sites_list:
            total_sites_count += 1
            site_dict["trial_id"] = existing_trial.trial_id
            site_id = site_dict["id"]

            existing_site = db.query(Site).filter(Site.id == site_id).first()
            if not existing_site:
                new_site = Site(**site_dict)
                db.add(new_site)
            else:
                for sk, sv in site_dict.items():
                    if hasattr(existing_site, sk):
                        setattr(existing_site, sk, sv)
            db.flush()

    logger.info(f"Successfully ingested {len(CTRI_DATASET)} CTRI trials and {total_sites_count} real research sites.")
    return total_sites_count
